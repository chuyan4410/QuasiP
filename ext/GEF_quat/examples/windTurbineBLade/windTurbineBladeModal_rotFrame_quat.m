%% NREL 5MW blade modal analysis with quaternion GEB in a rotating frame
% The sectional data are taken from:
% RefExamples/17ElmBld3WindModes(240103sealed)/sysStrutProp8.m
% RefExamples/17ElmBld3WindModes(240103sealed)/sysAeroProp8.m
clear
clc

%% Paths
thisFile = mfilename('fullpath');
exampleDir = fileparts(thisFile);
repoRoot = fileparts(fileparts(exampleDir));
addpath(genpath(fullfile(repoRoot, 'src')));
addpath(genpath(fullfile(repoRoot, 'ext')));

%% Analysis options
numModes = 12;
enableRotFrame = true;
rotSpeedRPM = 12.1 * 0;
OmegaHub = rotSpeedRPM * 2 * pi / 60;
gravity = [0; 0; 0];
reduce = 1;

%% NREL 5MW blade station data
blade = nrel5mwBladeSectionData();
radius = blade.radius(:);
elmnum = 17;
nodenum = numel(radius);
dof_sys = 7 * nodenum;

if nodenum ~= 2 * elmnum + 1
    error('The 17-element blade mesh expects 35 L3 nodes.');
end

%% Load data containers required by the node class
timenum = 1;
AMList = {{zeros(3,1), zeros(3,3)}};
gList = {{gravity}};
fList = {{zeros(6,1)}};
RM = [0; 0; 0];

%% Build OOP quaternion beam model
myNodes = cell(nodenum, 1);
q0 = zeros(7,1);
dq0 = zeros(7,1);
ddq0 = zeros(7,1);
dummyMaterial = Material.IsotropicLE(0, 0, 0);

for n = 1:nodenum
    sec = directRodSection(blade, n);
    mySection = CrossSection.DirectRod3D(sec.rhoA, sec.Jrho, sec.CA_mB, sec.CI_mB);

    dofID = transpose(7 * n - 6 : 7 * n);
    q0(:) = 0;
    q0(1) = radius(n);
    q0(4:7) = quatFromAxisAngle([1; 0; 0], deg2rad(blade.twist(n)));
    % q0(4:7) = [1; 0; 0; 0];

    myNodes{n} = Node.HM3DCurvRodNode_quat(dofID, dummyMaterial, mySection, ...
        RM, q0, dq0, ddq0, timenum, AMList, gList, fList, 1);
end

myElements = cell(elmnum, 1);
for e = 1:elmnum
    nodes = {myNodes{2*e-1}; myNodes{2*e}; myNodes{2*e+1}};
    myElements{e} = Element.HM3DCurvRodL3_quat(nodes, reduce);
end

if enableRotFrame
    % at t = 0 
    phi0 = 0;
    er   = [cos(phi0/2); 0; 0; sin(phi0/2)];
    der  = 0.5 * OmegaHub * [-sin(phi0/2); 0; 0; cos(phi0/2)];
    dder = -0.25 * OmegaHub^2 * [cos(phi0/2); 0; 0; sin(phi0/2)];
    % er = [1; 0; 0; 0];
    % der = [0; 0; 0; 0.5 * OmegaHub];
    % dder = [-0.25 * OmegaHub^2; 0; 0; 0];
    rotFrame = struct('enabled', true, ...
                      'e', er, ...
                      'de', der, ...
                      'dde', dder, ...
                      'Lambda', Base.genA(er), ...
                      'Omega', 2 * Base.genG(er) * der, ...
                      'dotOmega', 2 * Base.genG(er) * dder);
else
    rotFrame = struct('enabled', false);
end

for e = 1:elmnum
    myElements{e}.setRotationFrame(rotFrame);
end

%% Cantilever root constraint plus quaternion unit constraints
[q0_sys, dq0_sys, ddq0_sys] = Base.sysInitCond(myNodes);
dof_constraint = 6;
constrainedDOF = {{1, [1, 2, 3, 5, 6, 7]}};
dispSet = [radius(1); 0; 0; 0; 0; 0];
CqSet = zeros(dof_constraint, dof_sys);
CqSet(1:3, 1:3) = eye(3);
CqSet(4:6, 5:7) = eye(3);
KbSet = zeros(dof_sys, dof_sys);
dispList = {{dispSet, CqSet, KbSet}};
constrainedType = {{'displacement boundary'}; {[]}};
myDispConstraint = Constraint.Constraint(constrainedDOF, ...
    constrainedType, dispList, dof_constraint);

forcList = {{zeros(6,1)}};
dof_applied = {{nodenum, 2}};
myForcConstraint = Constraint.Constraint(dof_applied, ...
    {{'force boundary'}}, forcList, dof_constraint);

myConstraints.Dconstraints = myDispConstraint;
myConstraints.Fconstraints = myForcConstraint;

%% Assemble tangent stiffness and mass matrices at the undeformed state
myAssembly = Assembly.Assembly(myElements, myNodes, myConstraints, ...
    q0_sys, dq0_sys, ddq0_sys);
myAssembly.genSysMatVec(1);

M = full(myAssembly.M);
Kt = full(myAssembly.Kt);
Cq = full(myAssembly.Cq);

%% Modal analysis in the constrained subspace
U = null(Cq, 'r');
M_hat = U.' * M * U;
Kt_hat = U.' * Kt * U;

[V_hat, D_hat] = eig(Kt_hat, M_hat);
lambda = real(diag(D_hat));
valid = isfinite(lambda) & lambda > 0;
[omega, sortID] = sort(sqrt(lambda(valid)));
V_hat = V_hat(:, valid);
V_hat = V_hat(:, sortID);

freqHz = omega / (2 * pi);
numModes = min(numModes, numel(freqHz));
freqHz = freqHz(1:numModes);
omega = omega(1:numModes);
modeShape = U * V_hat(:, 1:numModes);

modalResults = table((1:numModes).', omega, freqHz, ...
    'VariableNames', {'Mode', 'CircularFrequency_rad_s', 'Frequency_Hz'});

disp('NREL 5MW blade modal frequencies from quaternion GEB:')
disp(modalResults)

%% Plot flapwise/edgewise displacement components of the first modes
figure('Name', 'NREL 5MW blade modes - quaternion GEB');
tiledlayout(3, 1)

% numPlotModes = 3;
nexttile
plot(radius, modeShape(3:7:end, [1;3;5]), 'LineWidth', 1.1)
xlabel('Blade radius (m)')
ylabel('Out-of-plane component')
grid on
title('Flapwise-like modal components')

nexttile
plot(radius, modeShape(2:7:end, [2;4]), 'LineWidth', 1.1)
xlabel('Blade radius (m)')
ylabel('In-plane component')
grid on
title('Edgewise-like modal components')

nexttile
plot(radius, modeShape(5:7:end, 6), 'LineWidth', 1.1)
xlabel('Blade radius (m)')
ylabel('torsional component')
grid on
title('Torsional-like modal components')

