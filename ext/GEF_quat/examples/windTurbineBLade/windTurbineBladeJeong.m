%% Jeong/Li-style NREL 5MW aeroelastic reproduction
% Rated operation with a JeongBEMT aerodynamic model. Set quickRun=false for
% the full 45 s run.
clear
clc

%% Paths
thisFile = mfilename('fullpath');
exampleDir = fileparts(thisFile);
repoRoot = fileparts(fileparts(exampleDir));
refDir = fullfile(exampleDir, 'OpenFAST_5MW_Baseline');
addpath(genpath(fullfile(repoRoot, 'src')));
addpath(genpath(fullfile(repoRoot, 'ext')));

%% Rated operation settings
rotSpeedRPM = 12.1;
OmegaHub = rotSpeedRPM * 2 * pi / 60;
hubWind = 11.4;
pitchDeg = 0;
preconeDeg = 2.5;
gravity = [0; -9.81*0; 0];
reduce = 1;

quickRun = 0;
if quickRun
    dt = 0.02;
    endTime = 0.2;
    loadRampTime = 0.5;
else
    dt = 0.01;
    endTime = 45;
    loadRampTime = 15;
end

t = 0:dt:endTime;
timenum = numel(t);

%% NREL 5MW blade structural station data
blade = nrel5mwBladeSectionData();
radius = blade.radius(:);
preconeRad = deg2rad(preconeDeg);
elmnum = 17;
nodenum = numel(radius);
dof_sys = 7 * nodenum;

if nodenum ~= 2 * elmnum + 1
    error('The 17-element blade mesh expects 35 L3 nodes.');
end

%% Load data containers required by the node class
AMList = repmat({{zeros(3,1), zeros(3,3)}}, timenum, 1);
gList = repmat({{gravity}}, timenum, 1);
fList = repmat({{zeros(6,1)}}, timenum, 1);
RM = [0; 0; 0];

%% Build OOP quaternion beam model
myNodes = cell(nodenum, 1);
q0 = zeros(7,1);
dq0 = zeros(7,1);
ddq0 = zeros(7,1);
dummyMaterial = Material.IsotropicLE(0, 0, 0);
qCone = quatFromAxisAngle([0; 1; 0], -preconeRad);

for n = 1:nodenum
    sec = directRodSection(blade, n);
    mySection = CrossSection.DirectRod3D(sec.rhoA, sec.Jrho, sec.CA_mB, sec.CI_mB);

    dofID = transpose(7 * n - 6 : 7 * n);
    q0(:) = 0;
    q0(1) = radius(n) * cos(preconeRad);
    q0(3) = radius(n) * sin(preconeRad);
    qTwist = quatFromAxisAngle([1; 0; 0], deg2rad(blade.twist(n)));
    q0(4:7) = Base.quatMultiply(qCone, qTwist);

    myNodes{n} = Node.HM3DCurvRodNode_quat(dofID, dummyMaterial, mySection, ...
        RM, q0, dq0, ddq0, timenum, AMList, gList, fList, 1);
end

myElements = cell(elmnum, 1);
for e = 1:elmnum
    nodes = {myNodes{2*e-1}; myNodes{2*e}; myNodes{2*e+1}};
    myElements{e} = Element.HM3DCurvRodL3_quat(nodes, reduce);
end

%% Constraints
[q0_sys, dq0_sys, ddq0_sys] = Base.sysInitCond(myNodes);
dof_constraint = 6;
constrainedDOF = {{1, [1, 2, 3, 5, 6, 7]}};
rootQuat0 = q0_sys(4:7);
rootPosition0 = [radius(1) * cos(preconeRad); 0; radius(1) * sin(preconeRad)];
dispSet = [rootPosition0; rootQuat0(2:4)];
CqSet = zeros(dof_constraint, dof_sys);
CqSet(1:3, 1:3) = eye(3);
CqSet(4:6, 5:7) = eye(3);
KbSet = zeros(dof_sys, dof_sys);
dispList = repmat({{dispSet, CqSet, KbSet}}, timenum, 1);
constrainedType = {{'displacement boundary'}; {[]}};
myDispConstraint = Constraint.Constraint(constrainedDOF, ...
    constrainedType, dispList, dof_constraint);

forcList = repmat({{zeros(6,1)}}, timenum, 1);
dof_applied = {{nodenum, 2}};
myForcConstraint = Constraint.Constraint(dof_applied, ...
    {{'force boundary'}}, forcList, dof_constraint);

myConstraints.Dconstraints = myDispConstraint;
myConstraints.Fconstraints = myForcConstraint;

%% Rotating frame history
rotationSign = 1; % clockwise/anti-clockwise in the current rotating-frame convention
rotFrame = prescribedPrimingRotatingFrame(t, OmegaHub, loadRampTime, rotationSign);

%% Quasi-steady BEMT model
aeroData = nrel5mwAeroData17(refDir);
aeroOptions = struct( ...
    'rho', 1.225, ...
    'bladeCount', 3, ...
    'rotorRadius', 63, ...
    'hubRadius', 1.5, ...
    'hubWind', hubWind, ...
    'omega', OmegaHub, ...
    'pitch', pitchDeg, ...
    'numGauss', 3, ...
    'inductionMode', 'quasiSteadyIterative', ...
    'includeTipLoss', true, ...
    'includeHubLoss', true, ...
    'includeGlauert', true, ...
    'glauertCriticalInduction', 0.2, ...
    'minimumLossFactor', 1e-3, ...
    'forceSign', struct('axial', -1, 'tangential', rotationSign), ...
    'pitchMomentSign', -rotationSign, ...
    'thetaDeformationSign', rotationSign, ...
    'tangentialVelocitySign', rotationSign, ...
    'momentDirectionMode', 'referenceSpan', ...
    'loadScale', min(t(:) / loadRampTime, 1), ...
    'time', t(:), ...
    'primingTime', loadRampTime, ...
    'spanAxis', 1, ...
    'tangentialAxis', 2, ...
    'axialAxis', 3, ...
    'airfoilInterpolationMode', 'blend');
aeroModel = Aero.JeongBEMT(aeroData, aeroOptions);

%% Time integration
solver = Solver.G_alpha(myElements, myNodes, myConstraints, dt, dof_sys);
solver.rho_s = 0.8;
solver.rotationFrame = rotFrame;
solver.aeroForceModel = aeroModel;
solver.aeroForceUpdateMode = 'timeStep';
solver.tol = 1e-4;
solver.max_it = 80;
solver.Damp = zeros(dof_sys);


tic
solver.Integrate(t);
toc

%%
tipZ = solver.Solution.q_sys(3:7:end, :) - q0_sys(3:7:end);
[thrust, torque] = rotorAeroLoadsFromHistory(solver.aeroForceHistory, radius, 3, aeroOptions);

fprintf('\nJeong/Li-style reproduction settings:\n');
fprintf('  Vhub = %.3f m/s, Omega = %.3f rpm, pitch = %.3f deg\n', ...
    hubWind, rotSpeedRPM, pitchDeg);
fprintf('  precone = %.3f deg\n', preconeDeg);
fprintf('  dt = %.4f s, Tf = %.3f s, ramp = %.3f s\n', dt, endTime, loadRampTime);
fprintf('  Final three-blade thrust estimate = %.6e N\n', thrust(end));
fprintf('  Final three-blade torque estimate = %.6e N-m\n', torque(end));

if ~quickRun
    revPeriod = 2 * pi / OmegaHub;
    lastRev = t >= max(0, endTime - revPeriod);
    fprintf('  Last-revolution mean thrust = %.6e N\n', mean(thrust(lastRev)));
    fprintf('  Last-revolution mean torque = %.6e N-m\n', mean(torque(lastRev)));
    fprintf('  Last-revolution mean power = %.6e W\n', mean(torque(lastRev)) * OmegaHub);
end

figure('Name', 'Jeong NREL 5MW aeroelastic reproduction');
tiledlayout(3, 1)

nexttile
plot(t, tipZ(end,:), 'LineWidth', 1.1)
xlabel('Time (s)')
ylabel('Tip axial disp. (m)')
grid on

nexttile
plot(t, thrust / 1e3, 'LineWidth', 1.1)
xlabel('Time (s)')
ylabel('3-blade thrust (kN)')
grid on

nexttile
plot(t, torque / 1e6, 'LineWidth', 1.1)
xlabel('Time (s)')
ylabel('3-blade torque (MN-m)')
grid on

%% Local helpers
function [thrust, torque] = rotorAeroLoadsFromHistory(aeroHistory, radius, bladeCount, aeroOptions)
    thrust = zeros(numel(aeroHistory), 1);
    torque = zeros(numel(aeroHistory), 1);

    valid = find(~cellfun(@isempty, aeroHistory), 1, 'first');
    if isempty(valid)
        return
    end

    [weights, ~] = Base.gaussQuadrature(aeroOptions.numGauss);
    elemnum = (numel(radius) - 1) / 2;
    for step = 1:numel(aeroHistory)
        if isempty(aeroHistory{step})
            continue
        end

        g = aeroHistory{step}.gauss;
        scale = aeroHistory{step}.loadScale;
        bladeThrust = 0;
        bladeTorque = 0;
        for e = 1:elemnum
            jac = (radius(2*e+1) - radius(2*e-1)) / 2;
            ids = find(g.elementID == e);
            for k = 1:numel(ids)
                id = ids(k);
                w = weights(g.gaussID(id));
                bladeThrust = bladeThrust + scale * g.normalForce(id) * w * jac;
                % Positive tangential force follows the rotating-frame +Y direction.
                bladeTorque = bladeTorque + scale * g.tangentialForce(id) * g.radius(id) * w * jac;
            end
        end
        thrust(step) = bladeCount * bladeThrust;
        torque(step) = bladeCount * bladeTorque;
    end
end

function rotFrame = prescribedPrimingRotatingFrame(t, omegaRated, rampTime, rotationSign)
    if nargin < 4
        rotationSign = 1;
    end
    e = zeros(4, numel(t));
    de = zeros(4, numel(t));
    dde = zeros(4, numel(t));
    for k = 1:numel(t)
        if t(k) < rampTime
            omega = rotationSign * omegaRated * t(k) / rampTime;
            dotOmega = rotationSign * omegaRated / rampTime;
            phi = 0.5 * rotationSign * omegaRated / rampTime * t(k)^2;
        else
            omega = rotationSign * omegaRated;
            dotOmega = 0;
            phi = rotationSign * (0.5 * omegaRated * rampTime ...
                + omegaRated * (t(k) - rampTime));
        end
        e(:,k) = [cos(phi/2); 0; 0; sin(phi/2)];
        de(:,k) = 0.5 * omega * [-sin(phi/2); 0; 0; cos(phi/2)];
        dde(:,k) = -0.25 * omega^2 * [cos(phi/2); 0; 0; sin(phi/2)] ...
            + 0.5 * dotOmega * [-sin(phi/2); 0; 0; cos(phi/2)];
    end
    rotFrame = struct('enabled', true, 'e', e, 'de', de, 'dde', dde);
end

