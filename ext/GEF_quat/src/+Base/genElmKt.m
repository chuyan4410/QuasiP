function Kt = genElmKt(c, e, G, r_prim, N, e_prim, ...
                            lambd, S_prim, N_prim, CA_mB, ...
                            CI_mB, gam, gam0, kap, kap0, numDOF)

[dgam_dq, dkap_dq] = Base.genElmdgam_dq(e, G, r_prim, N, e_prim, ...
    lambd, S_prim, N_prim);
Kt1 = c^2 * (dgam_dq.' * CA_mB * dgam_dq + ...
             dkap_dq.' * CI_mB * dkap_dq);
Kt = Kt1;
end